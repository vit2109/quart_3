"""Тесты постобработки LLM-текста."""

from infrastructure.ai.text_utils import dedupe_llm_output


def test_dedupe_repeated_section_title():
    text = """### Обзор данных

#### 1. **Данные о количестве входящих вызовов**

- **Субъекты РФ**: Большинство данных относятся к Ростовской области.
- **Количество вызовов**: 1-2 вызова в день.

#### 2. **Данные о количестве входящих вызовов**.

- **Субъекты РФ**: Большинство данных относятся к Ростовской области.
- **Количество вызовов**: 1-2 вызова в день."""
    out = dedupe_llm_output(text)
    assert "#### 2." not in out
    assert out.count("Ростовской") == 1
